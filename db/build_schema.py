#!/usr/bin/env python3
"""Regenerate db/schema.sql and db/reference-data.sql from migrations/*.sql, and verify them.

  python3 db/build_schema.py          # rebuild both files from the migrations (in order) on a fresh in-memory SQLite
  python3 db/build_schema.py --check  # rebuild in memory and compare: migrations vs schema.sql (+ reference-data.sql)

schema.sql creates the whole current schema in one go (tables, indexes, FTS5 search table, triggers, views) with no rows.
reference-data.sql holds only owner-curated reference rows that migrations seed (the popular-100 roster). It never contains
user, session, feedback, mail, fetch, inventory or analytics data. Production D1 should normally be built with
`npm run db:migrate:remote` (wrangler tracks applied migrations); schema.sql is for a fresh database or for review.
"""
import glob, os, sqlite3, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MIG = sorted(glob.glob(os.path.join(ROOT, "migrations", "*.sql")))
SCHEMA = os.path.join(ROOT, "db", "schema.sql")
REFDATA = os.path.join(ROOT, "db", "reference-data.sql")
REF_TABLES = ["perstore_popular"]   # reference rows seeded by migrations (owner-approved roster)

def from_migrations():
    c = sqlite3.connect(":memory:")
    for f in MIG:
        c.executescript(open(f, encoding="utf-8").read())
    return c

def schema_objects(c):
    """Every schema object except SQLite internals and FTS5 shadow tables (created by the virtual table itself)."""
    virt = [r[0] for r in c.execute("SELECT name FROM sqlite_master WHERE type='table' AND sql LIKE 'CREATE VIRTUAL TABLE%'")]
    rows = c.execute("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid").fetchall()
    out = []
    for t, n, tbl, sql in rows:
        if t == "table" and any(n.startswith(v + "_") and n[len(v) + 1:] in ("data", "idx", "content", "docsize", "config") for v in virt):
            continue
        out.append((t, n, tbl, sql))
    return out

def normalized(c):
    """Comparable schema: every object's type/name/table plus column info per table, independent of creation order."""
    objs = sorted((t, n, tbl, " ".join(sql.split())) for t, n, tbl, sql in schema_objects(c))
    cols = {}
    for t, n, _, _ in objs:
        if t == "table":
            cols[n] = c.execute(f"PRAGMA table_xinfo('{n}')").fetchall()
    return objs, cols

def write():
    c = from_migrations()
    objs = schema_objects(c)
    order = {"table": 0, "index": 1, "view": 2, "trigger": 3}
    # Tables in creation order first (foreign keys may point backwards), then indexes, views, triggers.
    objs = sorted(objs, key=lambda o: order.get(o[0], 9))
    with open(SCHEMA, "w", encoding="utf-8") as fh:
        fh.write("-- Utah Remedy D1 schema: the result of migrations/0001..%s applied in order.\n" % os.path.basename(MIG[-1])[:4])
        fh.write("-- Generated by db/build_schema.py (do not edit by hand; add a migration, then regenerate).\n")
        fh.write("-- Creates every table, index, FTS5 table, view and trigger. No rows. Reference rows: db/reference-data.sql.\n\n")
        fh.write("PRAGMA defer_foreign_keys = true;\n\n")
        for t, n, tbl, sql in objs:
            fh.write(sql.strip() + ";\n\n")
    with open(REFDATA, "w", encoding="utf-8") as fh:
        fh.write("-- Utah Remedy reference data (owner-curated rows that the migrations seed). Generated by db/build_schema.py.\n")
        fh.write("-- Contains no user, session, feedback, mail, fetch, inventory or analytics data.\n\n")
        for tbl in REF_TABLES:
            cols = [r[1] for r in c.execute(f"PRAGMA table_info('{tbl}')")]
            for row in c.execute(f"SELECT {', '.join(cols)} FROM {tbl} ORDER BY rowid"):
                vals = ", ".join("NULL" if v is None else str(v) if isinstance(v, (int, float)) else "'" + str(v).replace("'", "''") + "'" for v in row)
                fh.write(f"INSERT OR IGNORE INTO {tbl} ({', '.join(cols)}) VALUES ({vals});\n")
    print(f"wrote {os.path.relpath(SCHEMA, ROOT)} ({len(objs)} objects) and {os.path.relpath(REFDATA, ROOT)}")

def check():
    a = from_migrations()
    b = sqlite3.connect(":memory:")
    b.executescript(open(SCHEMA, encoding="utf-8").read())
    b.executescript(open(REFDATA, encoding="utf-8").read())
    ok = normalized(a) == normalized(b)
    data_ok = True
    for tbl in [r[0] for r in a.execute("SELECT name FROM sqlite_master WHERE type='table'")]:
        try:
            ra = sorted(map(repr, a.execute(f"SELECT * FROM '{tbl}'")))
            rb = sorted(map(repr, b.execute(f"SELECT * FROM '{tbl}'")))
        except sqlite3.Error:
            continue
        if ra != rb:
            data_ok = False; print(f"  rows differ in {tbl}: migrations {len(ra)} vs schema+reference {len(rb)}")
    na = len(schema_objects(a))
    print(f"schema objects: {na}; schema identical: {ok}; rows identical: {data_ok}")
    sys.exit(0 if ok and data_ok else 1)

if __name__ == "__main__":
    check() if "--check" in sys.argv else write()
