ALTER TABLE perstore_state ADD COLUMN b1_total INTEGER;
ALTER TABLE perstore_state ADD COLUMN popular_total INTEGER NOT NULL DEFAULT 0;
ALTER TABLE perstore_state ADD COLUMN popular_note TEXT;

