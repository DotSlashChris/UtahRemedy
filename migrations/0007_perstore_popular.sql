-- 0007: popular-100 per-store refresh list (owner-approved 2026-10-22; docs/popular-100-starter.csv @ 9cb1268). ADDITIVE ONLY.
--
-- perstore_popular is the roster. The ACTIVE list (max 100) = every locked entry + the best-ranked unlocked entries,
-- computed at query time (src/fetchers/popular.ts). Entries past 100 stay as inactive reserve, never deleted.
-- locked = 1: admin lock. Always in the active list, can't be removed (trigger below); any future rotation must skip it.
CREATE TABLE IF NOT EXISTS perstore_popular (
  sku        TEXT PRIMARY KEY,
  rank       INTEGER NOT NULL,             -- lower = higher priority (fetch order among unlocked)
  locked     INTEGER NOT NULL DEFAULT 0 CHECK (locked IN (0, 1)),
  source     TEXT NOT NULL DEFAULT 'starter', -- starter | admin | rotation (future)
  note       TEXT,
  added_at   TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_popular_active ON perstore_popular (locked DESC, rank, sku);

-- Locked entries can't be deleted by anything (admin remove, future weekly rotation). Unlock first.
CREATE TRIGGER IF NOT EXISTS perstore_popular_keep_locked BEFORE DELETE ON perstore_popular
WHEN OLD.locked = 1 BEGIN SELECT RAISE(ABORT, 'perstore_popular: locked entry cannot be removed'); END;

